[BITS 16]                  ; Режим реального адреса (16 бит)
[ORG 0x7C00]               ; BIOS загружает нас по адресу 0x7C00

; ------------------------------------------------------------
; Константы
; ------------------------------------------------------------
KERNEL_LBA_START equ 1     ; Номер первого сектора ядра (LBA) – сразу после загрузчика
KERNEL_SECTOR_COUNT equ 64 ; Сколько секторов читать (по 512 байт) – можно увеличить
KERNEL_LOAD_SEG    equ 0x1000 ; Сегмент, куда грузим ядро (0x1000:0x0000)
KERNEL_LOAD_OFF    equ 0x0000 ; Смещение (в итоге физический адрес 0x10000)
STACK_TOP          equ 0x90000 ; Верхушка стека в защищённом режиме

; ------------------------------------------------------------
; Точка входа
; ------------------------------------------------------------
start:
    cli                      ; Запрещаем прерывания – пока не настроим стек и GDT
    xor ax, ax               ; Обнуляем AX
    mov ds, ax               ; DS = 0 (сегмент данных – на начало памяти)
    mov es, ax               ; ES = 0 (для работы с LBA-пакетом)
    mov ss, ax               ; SS = 0
    mov sp, 0x7C00           ; Временный стек (растёт вниз от 0x7C00)
    sti                      ; Разрешаем прерывания (можно, т.к. стек уже есть)

    ; Сохраняем номер диска, с которого нас загрузили (в DL)
    mov [boot_drive], dl

    ; Очищаем экран (видеорежим 80x25)
    mov ax, 0x0003
    int 0x10                 ; Прерывание BIOS: установить текстовый режим 3

    mov si, msg_loading
    call print_string_16

    ; --------------------------------------------------------
    ; Загрузка ядра через LBA (расширение Int 13h, AH=0x42)
    ; --------------------------------------------------------
    ; Проверяем, поддерживает ли BIOS расширения LBA
    ; Вызов: AH=0x41, BX=0x55AA, DL=диск
    mov ah, 0x41
    mov bx, 0x55AA
    mov dl, [boot_drive]
    int 0x13
    jc .no_lba               ; Если CF=1 – LBA не поддерживается
    cmp bx, 0xAA55           ; Расширение должно вернуть 0xAA55 в BX
    jne .no_lba

    ; Поддерживается – используем функцию 0x42 (чтение с LBA)
    mov si, lba_packet       ; DS:SI указывает на структуру пакета
    mov ah, 0x42
    mov dl, [boot_drive]
    int 0x13
    jc disk_error            ; Если ошибка – сообщаем и зависаем
    jmp .lba_ok

.no_lba:
    ; Если LBA не поддерживается – падаем с сообщением
    mov si, msg_no_lba
    call print_string_16
    jmp $

.lba_ok:
    ; Успешно загрузили ядро. Теперь переходим в защищённый режим.
    cli
    lgdt [gdt_descriptor]    ; Загружаем таблицу GDT

    ; Включаем защищённый режим (устанавливаем бит PE в CR0)
    mov eax, cr0
    or eax, 1
    mov cr0, eax

    ; Дальний прыжок для перезагрузки сегментных регистров
    ; После этого процессор работает в 32-битном режиме

    jmp CODE_SEG:protected_mode

; ------------------------------------------------------------
; 16-битные подпрограммы
; ------------------------------------------------------------

; отладчик
debug:
    mov si, msg_her
    call print_string_16
    ret

; Печать строки с нулевым терминатором (через BIOS)
print_string_16:
    pusha
    mov ah, 0x0E             ; Функция BIOS: телетайпный вывод
.loop:
    lodsb                    ; Загружаем байт из [SI] в AL, увеличиваем SI
    test al, al              ; Проверяем, не конец строки (AL == 0)?
    jz .done
    int 0x10                 ; Вызов BIOS для печати символа
    jmp .loop
.done:
    popa
    ret

; Обработчик ошибки чтения диска
disk_error:
    mov si, msg_disk_error
    call print_string_16
    jmp $                    ; Бесконечный цикл

; ------------------------------------------------------------
; Данные (в реальном режиме)
; ------------------------------------------------------------
boot_drive  db 0
msg_loading db "Loading kernel via LBA...", 0x0D, 0x0A, 0
msg_no_lba  db "LBA not supported!", 0x0D, 0x0A, 0
msg_disk_error db "Disk read error!", 0x0D, 0x0A, 0
msg_her db "хер", 0x0D, 0x0A, 0

; ------------------------------------------------------------
; Структура LBA-пакета для Int 0x13 AH=0x42
; ------------------------------------------------------------
; Формат (16 байт):
;   Offset 0:  размер пакета (16)
;   Offset 2:  количество секторов для чтения
;   Offset 4:  смещение буфера (сегмент:смещение)
;   Offset 6:  сегмент буфера
;   Offset 8:  LBA (нижние 32 бита)
;   Offset 12: LBA (верхние 32 бита – для 64-битных LBA, обычно 0)
; ------------------------------------------------------------
lba_packet:
    db 0x10                  ; Размер пакета (16 байт)
    db 0x00                  ; Зарезервировано (0)
    dw KERNEL_SECTOR_COUNT   ; Количество секторов для чтения
    dw KERNEL_LOAD_OFF       ; Смещение буфера (0x0000)
    dw KERNEL_LOAD_SEG       ; Сегмент буфера (0x1000)
    dd KERNEL_LBA_START      ; Номер начального LBA (младшие 32 бита)
    dd 0x00000000            ; Старшие 32 бита LBA (не нужны)

; ------------------------------------------------------------
; GDT (Global Descriptor Table) – минимальная для защищённого режима
; ------------------------------------------------------------
gdt_start:
    ; Нулевой дескриптор (обязателен)
    dd 0x00000000
    dd 0x00000000

; Дескриптор сегмента кода (32-битный, исполняемый, не системный)
gdt_code:
    dw 0xFFFF                ; Лимит (биты 0-15) – 4 ГБ
    dw 0x0000                ; База (биты 0-15)
    db 0x00                  ; База (биты 16-23)
    db 10011010b             ; Флаги доступа: Present, Privilege 0, Code, Readable
    db 11001111b             ; Флаги: 32-битный, гранулярность 4 КБ
    db 0x00                  ; База (биты 24-31)

; Дескриптор сегмента данных (32-битный, читаемый/записываемый)
gdt_data:
    dw 0xFFFF
    dw 0x0000
    db 0x00
    db 10010010b             ; Present, Privilege 0, Data, Writable
    db 11001111b
    db 0x00

gdt_end:

gdt_descriptor:
    dw gdt_end - gdt_start - 1 ; Размер GDT (в байтах - 1)
    dd gdt_start               ; Адрес начала GDT

; Селекторы для загрузки в CS и другие сегментные регистры
CODE_SEG equ gdt_code - gdt_start
DATA_SEG equ gdt_data - gdt_start

; ------------------------------------------------------------
; 32-битный защищённый режим
; ------------------------------------------------------------
[BITS 32]

%macro debug_P 0
    ; --- ОТЛАДКА: выводим символ 'P' в левый верхний угол ---
    mov word [0xB8000], 0x0F50   ; 'P' белым по чёрному
%endmacro

protected_mode:

    ; Загружаем селекторы данных во все сегментные регистры
    mov ax, DATA_SEG
    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax
    mov ss, ax

    ; Настраиваем стек (растёт вниз)
    mov ebp, STACK_TOP
    mov esp, ebp


    ; Передаём управление ядру (оно лежит по адресу 0x10000)
    ; ВАЖНО: ядро должно быть скомпилировано как плоский двоичный файл
    ; и его точка входа должна находиться по смещению 0 от начала.
    call KERNEL_LOAD_SEG << 4   ; Эквивалент call 0x10000
    ; (KERNEL_LOAD_SEG = 0x1000, смещение 0 -> физический адрес 0x10000)

    ; Если ядро вернёт управление (не должно) – зависаем
    cli
.hang:
    hlt
    jmp .hang

; ------------------------------------------------------------
; Заполнение до 510 байт и сигнатура 0xAA55
; ------------------------------------------------------------
times 510 - ($-$$) db 0
dw 0xAA55
