#include "gdt_initialiser.h"
#include "konsole.h"
#include "system.h"

#pragma GCC optimize("no-optimize-sibling-calls")

// Number of GDT entries
#define GDT_COUNT 5
// Number of IDT entries
#define IDT_COUNT 256

static void gdt_set_gate(int32_t, uint32_t, uint32_t, uint8_t, uint8_t);

gdt_entry_t gdt_entries[GDT_COUNT];
gdt_ptr_t gdt_ptr;

static void gdt_flush(uint32_t gdt_ptr)
{
    asm volatile(
        "lgdt (%0)\n\t"       // Загружаем новый GDT-дескриптор из памяти
        "mov $0x10, %%ax\n\t" // 0x10 — селектор сегмента данных в новой GDT
        "mov %%ax, %%ds\n\t"  // Загружаем сегменты данных
        "mov %%ax, %%es\n\t"
        "mov %%ax, %%fs\n\t"
        "mov %%ax, %%gs\n\t"
        "mov %%ax, %%ss\n\t"
        "ljmp $0x08, $1f\n\t" // Дальний прыжок для перезагрузки CS с селектором 0x08 (селектор кода)
        "1:\n\t"              // Метка, куда прыгаем
        :
        : "r"(gdt_ptr)    // Передаём указатель в любой свободный регистр
        : "eax", "memory" // Регистр eax изменён, память изменена (GDT)
    );
}

void gdt_init(void)
{
    gdt_ptr.limit = (sizeof(gdt_entry_t) * GDT_COUNT) - 1;
    gdt_ptr.base = (uint32_t)&gdt_entries;

    // ------------------------------------------------------------------
    // Инициализация дескрипторов GDT
    // Каждый дескриптор описывает сегмент: базовый адрес, лимит, права.
    // Все сегменты используют плоскую модель: база = 0, лимит = 4 ГБ,
    // но отличаются правами доступа и уровнями привилегий (DPL).
    // ------------------------------------------------------------------

    // Нулевой дескриптор (обязателен по архитектуре x86).
    // Селектор 0x00 никогда не должен загружаться в сегментный регистр,
    // иначе процессор сгенерирует исключение #GP (General Protection Fault).
    // Все поля равны 0.
    gdt_set_gate(0, 0, 0, 0, 0);

    // ------------------------------------------------------------------
    // Сегмент кода ядра (Ring 0)
    // Индекс в GDT = 1, селектор = 0x08 (0x01 << 3, RPL=0)
    // Используется для выполнения кода операционной системы.
    // ------------------------------------------------------------------
    gdt_set_gate(1,          // номер дескриптора
                 0,          // база = 0 (линейный адрес начала сегмента)
                 0xFFFFFFFF, // лимит = 4 ГБ (максимальный размер сегмента)
                 0x9A,       // байт доступа (access)
                 0xCF);      // байт гранулярности (granularity)

    /* РАСШИФРОВКА access = 0x9A (1001 1010):
       - Бит 7 (P)    = 1 → сегмент присутствует в памяти (Present).
       - Биты 6-5     = 00 → DPL = 0 (привилегированный уровень ядра).
       - Бит 4 (S)    = 1 → дескриптор сегмента кода/данных (не системный).
       - Бит 3 (EX)   = 1 → сегмент исполняемый (код).
       - Бит 2 (DC)   = 0 → сегмент не подчиняющийся (non-conforming):
                              переход из менее привилегированного кода запрещён.
       - Бит 1 (RW)   = 1 → сегмент доступен для чтения (чтение данных из сегмента кода разрешено).
       - Бит 0 (AC)   = 0 → Accessed (устанавливается процессором, изначально 0).
    */

    /* РАСШИФРОВКА granularity = 0xCF (1100 1111):
       - Бит 7 (G)    = 1 → гранулярность 4 КБ (лимит умножается на 4096).
                              Тогда лимит 0xFFFFF * 4096 = 4 ГБ.
       - Бит 6 (D/B)  = 1 → 32-битный сегмент (используются EIP, ESP и 32-битные операнды по умолчанию).
       - Бит 5 (L)    = 0 → не 64-битный (для IA-32e не используется).
       - Бит 4 (AVL)  = 0 → зарезервировано для ОС (игнорируется процессором).
       - Биты 3-0     = 0xF → старшие 4 бита лимита (дополняют 20-битный лимит).
    */

    // ------------------------------------------------------------------
    // Сегмент данных ядра (Ring 0)
    // Индекс = 2, селектор = 0x10 (0x02 << 3)
    // Используется для данных, стека, глобальных переменных ядра.
    // ------------------------------------------------------------------
    gdt_set_gate(2, 0, 0xFFFFFFFF, 0x92, 0xCF);

    /* access = 0x92 (1001 0010):
       - Бит 7 (P)    = 1 → Present.
       - Биты 6-5     = 00 → DPL = 0 (ядро).
       - Бит 4 (S)    = 1 → сегмент данных/кода.
       - Бит 3 (EX)   = 0 → сегмент данных (не исполняемый).
       - Бит 2 (DC)   = 0 → направление роста вверх (обычный сегмент данных).
       - Бит 1 (RW)   = 1 → запись разрешена (Read/Write).
       - Бит 0 (AC)   = 0 → Accessed = 0.
    */

    // ------------------------------------------------------------------
    // Сегмент кода пользовательского режима (Ring 3)
    // Индекс = 3, селектор = 0x1B (0x03 << 3 | 0x03, если RPL=3)
    // Используется для выполнения приложений в кольце 3.
    // ------------------------------------------------------------------
    gdt_set_gate(3, 0, 0xFFFFFFFF, 0xFA, 0xCF);

    /* access = 0xFA (1111 1010):
       - Бит 7 (P)    = 1 → Present.
       - Биты 6-5     = 11 → DPL = 3 (пользовательский режим).
       - Бит 4 (S)    = 1 → сегмент кода/данных.
       - Бит 3 (EX)   = 1 → исполняемый (код).
       - Бит 2 (DC)   = 0 → не подчиняющийся (переход из кольца 3 в это сегмент разрешён только через шлюз).
       - Бит 1 (RW)   = 1 → чтение разрешено.
       - Бит 0 (AC)   = 0 → Accessed = 0.
    */

    // ------------------------------------------------------------------
    // Сегмент данных пользовательского режима (Ring 3)
    // Индекс = 4, селектор = 0x23 (0x04 << 3 | 0x03)
    // Используется для данных, стека пользовательских процессов.
    // ------------------------------------------------------------------
    gdt_set_gate(4, 0, 0xFFFFFFFF, 0xF2, 0xCF);

    /* access = 0xF2 (1111 0010):
       - Бит 7 (P)    = 1 → Present.
       - Биты 6-5     = 11 → DPL = 3 (пользовательский).
       - Бит 4 (S)    = 1 → сегмент данных.
       - Бит 3 (EX)   = 0 → данные.
       - Бит 2 (DC)   = 0 → рост вверх.
       - Бит 1 (RW)   = 1 → запись разрешена.
       - Бит 0 (AC)   = 0 → Accessed = 0.
    */

    /*
       Примечание:
       - Сегменты кода с DPL=3 позволяют пользовательскому коду выполняться,
         но для переключения из кольца 3 в кольцо 0 (например, для системных вызовов)
         необходимо использовать шлюзы прерываний (IDT) или инструкции sysenter/sysexit.
       - Сегменты данных с DPL=3 используются для пользовательских данных и стека.
       - Селекторы для пользовательского режима будут иметь RPL=3 (т.е. 0x1B и 0x23).
    */

    gdt_flush((uint32_t)&gdt_ptr);
}

static void gdt_set_gate(int32_t number, uint32_t base, uint32_t limit, uint8_t access, uint8_t granularity)
{
    gdt_entries[number].base_low = (base & 0xFFFF);
    gdt_entries[number].base_middle = (base >> 16) & 0xFF;
    gdt_entries[number].base_high = (base >> 24) & 0xFF;

    gdt_entries[number].limit_low = (limit & 0xFFFF);

    gdt_entries[number].granularity = (limit >> 16) & 0x0F;
    gdt_entries[number].granularity |= granularity & 0xF0;

    gdt_entries[number].access = access;
}